import AppKit

/// Bridges the system pasteboard to the clipboard bridge's protocols.
struct PasteboardWriter: ClipboardWriting {
    func write(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }
}

struct PasteboardReader: ClipboardReading {
    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    func read() -> String? {
        NSPasteboard.general.string(forType: .string)
    }

    func readImagePNG() -> Data? {
        let pasteboard = NSPasteboard.general
        if let png = pasteboard.data(forType: .png), !png.isEmpty {
            return png
        }
        guard let image = NSImage(pasteboard: pasteboard),
              let tiff = image.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else {
            return nil
        }
        return bitmap.representation(using: .png, properties: [:])
    }

    var changeCount: Int {
        NSPasteboard.general.changeCount
    }

    var isConcealed: Bool {
        guard let types = NSPasteboard.general.types else { return false }
        return types.contains { Self.concealedTypes.contains($0) }
    }
}
